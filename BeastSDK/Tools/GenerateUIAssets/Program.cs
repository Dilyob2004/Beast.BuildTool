using Beast.BuildTool;
using System.Reflection;
using System.Security.Cryptography;
using System.Text;

// SDK maintainer command, run from repository root. Normal app builds use the
// checked-in generated assets and do NOT require shader tools for built-in UI.
string sdk = Path.GetFullPath("BeastSDK");
string output = Path.Combine(sdk, "Source", "UI", "Private");
string work = Path.Combine(sdk, "Intermediate", "UIAssets");
Directory.CreateDirectory(Path.Combine(work, "Source"));
BuildConfigManager.LoadConfig(work);
var module = new ModuleRules();
module.Shaders.Add(new() { Name = "BuiltinUIVertex", Source = Path.Combine(output, "UI.hlsl"), Stage = ShaderStage.Vertex, EntryPoint = "VSMain" });
module.Shaders.Add(new() { Name = "BuiltinUIFragment", Source = Path.Combine(output, "UI.hlsl"), Stage = ShaderStage.Fragment, EntryPoint = "PSMain" });
module.Shaders.Add(new() { Name = "BuiltinUIShape", Source = Path.Combine(output, "UIShape.hlsl"), Stage = ShaderStage.Fragment, EntryPoint = "ShapeMain" });
module.Shaders.Add(new() { Name = "BuiltinUILayer", Source = Path.Combine(output, "UIShape.hlsl"), Stage = ShaderStage.Fragment, EntryPoint = "LayerMain" });
var compiler = typeof(ModuleRules).Assembly.GetType("Beast.BuildTool.ShaderCompiler", true)!;
var build = compiler.GetMethod("BuildAsync", BindingFlags.Public | BindingFlags.Static)!;
string shaderHeader = (await (Task<string?>)build.Invoke(null, [work, "Portable", TargetConfiguration.Release, new[] { module }])!)!;
void Write(string name, string value) {
    string path = Path.Combine(output, name);
    if (!File.Exists(path) || File.ReadAllText(path) != value) File.WriteAllText(path, value, new UTF8Encoding(false));
}
Write("UIShaders.generated.h", "// Generated by BeastSDK/Tools/GenerateUIAssets. Do not edit.\n" +
    File.ReadAllText(shaderHeader).Replace("namespace BeastShaders", "namespace Beast::UI::Detail::Shaders"));
byte[] font = File.ReadAllBytes(Path.Combine(sdk, "ThirdParty", "NotoSans", "NotoSans-Regular.ttf"));
const string expected = "B85C38ECEA8A7CFB39C24E395A4007474FA5A4FC864F6EE33309EB4948D232D5";
if (Convert.ToHexString(SHA256.HashData(font)) != expected) throw new Exception("Unexpected font hash. Review the font and license before updating this generator.");
var header = new StringBuilder("// Generated from unmodified NotoSans-Regular.ttf (SIL OFL 1.1).\n// See BeastSDK/ThirdParty/NotoSans/LICENSE. Do not edit.\n#pragma once\nnamespace Beast::UI::Detail {\ninline constexpr unsigned char FontBytes[] = {\n");
for (int i = 0; i < font.Length; ++i) {
    if (i % 24 == 0) header.Append("\n    ");
    header.Append("0x").Append(font[i].ToString("x2")).Append(',');
}
header.Append("\n};\n}\n");
Write("UIFontData.generated.h", header.ToString());
foreach (var extra in new[] {
    ("NotoSans/NotoSans-Bold.ttf", "FontBoldBytes", "UIFontBold.generated.h", "C976E4B1B99EDC88775377FCC21692CA4BFA46B6D6CA6522BFDA505B28FF9D6A"),
    ("MaterialIcons/MaterialIcons-Subset.otf", "FontIconBytes", "UIIcons.generated.h", "849B3EBD99D7F7ACEEC962CFD26A39A32AFC806B73407EF810CC2896F3FFE9DB") }) {
    byte[] bytes = File.ReadAllBytes(Path.Combine(sdk, "ThirdParty", extra.Item1));
    if (Convert.ToHexString(SHA256.HashData(bytes)) != extra.Item4) throw new Exception("Unexpected font hash: " + extra.Item1);
    var data = new StringBuilder($"// Generated from {extra.Item1}. See its ThirdParty license. Do not edit.\n#pragma once\nnamespace Beast::UI::Detail {{\ninline constexpr unsigned char {extra.Item2}[] = {{\n");
    for (int i = 0; i < bytes.Length; ++i) {
        if (i % 24 == 0) data.Append("\n    ");
        data.Append("0x").Append(bytes[i].ToString("x2")).Append(',');
    }
    data.Append("\n};\n}\n"); Write(extra.Item3, data.ToString());
}
Console.WriteLine("Generated portable UI shaders and trusted embedded fonts/icons.");
