param([switch]$Download)
$ErrorActionPreference = 'Stop'
$sdk = Split-Path $PSScriptRoot -Parent
$directory = Join-Path $sdk 'ThirdParty/NotoFallback'
New-Item -ItemType Directory -Force $directory | Out-Null
$revision = 'ffebf8c1ee449e544955a7e813c54f9b73848eac'
$fonts = @(
    @('NotoSansDevanagari', 'Regular', 'FontDevanagariBytes', '385E78E6359A9D88A0F243D53B1209D7548361BA2194E2B9EC779BCAA7E8949D'),
    @('NotoSansDevanagari', 'Bold', 'FontDevanagariBoldBytes', '19CC835A064C4AF63E3C20FEB54F5BF51DC25FFA52C0F493A23904572AF8B26E'),
    @('NotoSansSymbols2', 'Regular', 'FontSymbolsBytes', '630846D528DBE4C4981370A4D0A9475A1FD1491A129BB411F8E157CDB5DE13C6'),
    @('NotoSansArabic', 'Regular', 'FontArabicBytes', 'CEEA25B464A656DC3B26849BAB9356740401AF62AEDF1BFA8B7F0D9B75925B1B'),
    @('NotoSansArabic', 'Bold', 'FontArabicBoldBytes', 'ED2711B387750AE991B6A980B8DD16FDD65E6702B97E9F52ADF3A8EDF09EF4DF'),
    @('NotoSansHebrew', 'Regular', 'FontHebrewBytes', 'A7FA16FFFB27BEDB060A0866267C29E9859AEB9C21CC33F5B3AAF6EB062ECA85'),
    @('NotoSansHebrew', 'Bold', 'FontHebrewBoldBytes', 'A30243D1C625EAF63BB889F036FE9DE97E81D9248976F89E6E4252F9668C832E')
)
if ($Download) {
    foreach ($font in $fonts) {
        $file = "$($font[0])-$($font[1]).ttf"
        Invoke-WebRequest "https://raw.githubusercontent.com/notofonts/noto-fonts/$revision/hinted/ttf/$($font[0])/$file" -OutFile (Join-Path $directory $file)
    }
    Invoke-WebRequest "https://raw.githubusercontent.com/notofonts/noto-fonts/$revision/LICENSE" -OutFile (Join-Path $directory 'LICENSE')
}
$output = [Text.StringBuilder]::new("// Generated by BeastSDK/Tools/GenerateFallbackFonts.ps1. Do not edit.`n// Noto fonts (SIL OFL 1.1): ThirdParty/NotoFallback/LICENSE.`n#pragma once`nnamespace Beast::UI::Detail {`n")
foreach ($font in $fonts) {
    $file = Join-Path $directory "$($font[0])-$($font[1]).ttf"
    $hash = (Get-FileHash $file -Algorithm SHA256).Hash
    if ($hash -ne $font[3]) { throw "Unexpected font hash: $file" }
    $bytes = [IO.File]::ReadAllBytes($file)
    [void]$output.AppendLine("inline constexpr unsigned char $($font[2])[] = {")
    for ($i = 0; $i -lt $bytes.Length; ++$i) {
        if ($i % 24 -eq 0) { [void]$output.Append("`n    ") }
        [void]$output.Append(('0x{0:x2},' -f $bytes[$i]))
    }
    [void]$output.AppendLine("`n};")
}
[void]$output.AppendLine('}')
[IO.File]::WriteAllText((Join-Path $sdk 'Source/UI/Private/UIFallbackFonts.generated.h'), $output.ToString().Replace("`r`n", "`n"), [Text.UTF8Encoding]::new($false))
