param([switch]$Download)
$ErrorActionPreference = 'Stop'
$sdk = Split-Path $PSScriptRoot -Parent
$data = Join-Path $sdk 'ThirdParty/Unicode/17.0.0'
New-Item -ItemType Directory -Force $data | Out-Null
$files = @('auxiliary/GraphemeBreakProperty.txt', 'auxiliary/WordBreakProperty.txt', 'DerivedCoreProperties.txt', 'emoji/emoji-data.txt', 'auxiliary/GraphemeBreakTest.txt', 'auxiliary/WordBreakTest.txt')
if ($Download) {
    foreach ($file in $files) { Invoke-WebRequest "https://www.unicode.org/Public/17.0.0/ucd/$file" -OutFile (Join-Path $data (Split-Path $file -Leaf)) }
    Invoke-WebRequest 'https://www.unicode.org/license.txt' -OutFile (Join-Path $data '../LICENSE')
}
$output = [System.Text.StringBuilder]::new()
[void]$output.AppendLine('// Generated by BeastSDK/Tools/GenerateUnicode.ps1; Unicode 17.0.0. Do not edit.')
[void]$output.AppendLine('// Unicode data license: BeastSDK/ThirdParty/Unicode/LICENSE.')
[void]$output.AppendLine('#pragma once')
[void]$output.AppendLine('#include <cstdint>')
[void]$output.AppendLine('namespace Beast::UI::Detail::UnicodeData {')
foreach ($table in @(
    @{ Name='G'; File='GraphemeBreakProperty.txt'; Filter='' },
    @{ Name='W'; File='WordBreakProperty.txt'; Filter='' },
    @{ Name='I'; File='DerivedCoreProperties.txt'; Filter='InCB' },
    @{ Name='E'; File='emoji-data.txt'; Filter='Extended_Pictographic' }
)) {
    $ranges = @(foreach ($line in Get-Content (Join-Path $data $table.File)) {
        $fields = ($line.Split('#')[0]).Split(';').Trim()
        if ($fields.Count -lt 2 -or ($table.Filter -and $fields[1] -ne $table.Filter)) { continue }
        $ends = $fields[0] -split '\.\.'
        $prop = if ($table.Name -eq 'I') { $fields[2] } elseif ($table.Name -eq 'E') { 'Yes' } else { $fields[1] }
        [pscustomobject]@{ First=[Convert]::ToUInt32($ends[0],16); Last=[Convert]::ToUInt32($ends[-1],16); Prop=$prop }
    }) | Sort-Object First
    $props = @('Other') + @($ranges.Prop | Sort-Object -Unique)
    [void]$output.AppendLine("enum class $($table.Name) : std::uint8_t { $($props -join ', ') };")
    [void]$output.AppendLine("struct $($table.Name)Range { char32_t first, last; $($table.Name) value; };")
    [void]$output.AppendLine("inline constexpr $($table.Name)Range $($table.Name)Ranges[] = {")
    foreach ($range in $ranges) { [void]$output.AppendLine(('    {{0x{0:X}, 0x{1:X}, {2}::{3}}},' -f $range.First,$range.Last,$table.Name,$range.Prop)) }
    [void]$output.AppendLine('};')
}
[void]$output.AppendLine('}')
[IO.File]::WriteAllText((Join-Path $sdk 'Source/UI/Private/UnicodeData.h'), $output.ToString().Replace("`r`n","`n"), [Text.UTF8Encoding]::new($false))
Write-Host 'Generated Unicode 17.0.0 segmentation tables.'
